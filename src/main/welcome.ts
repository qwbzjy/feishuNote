export function welcomeMarkdownFor(platform: string): string {
  if (platform === 'darwin') return WELCOME_MARKDOWN
  return WELCOME_MARKDOWN
    .replace(/⌘ ⇧ /g, 'Ctrl+Shift+')
    .replace(/⌘ ⌥ /g, 'Ctrl+Alt+')
    .replace(/⌘ \\\\/g, 'Ctrl+\\\\')
    .replace(/⌘ /g, 'Ctrl+')
    .replace(/⌘/g, 'Ctrl')
}
